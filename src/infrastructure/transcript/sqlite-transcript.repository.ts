/**
 * SqliteTranscriptRepository - SQLite implementation of transcript cache
 */

import type { CacheConfig } from '@config/schema.js';
import { AppError, ErrorCodes } from '@core/errors/index.js';
import type { Result } from '@core/utils/result.js';
import { err, ok } from '@core/utils/result.js';
import { LanguageCode } from '@domain/transcript/language-code.js';
import type { TranscriptRepositoryPort } from '@domain/transcript/ports/transcript-repository.port.js';
import { Transcript } from '@domain/transcript/transcript.js';
import { VideoId } from '@domain/transcript/video-id.js';
import Database from 'better-sqlite3';
import { mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

/**
 * SQLite transcript repository
 * Stores transcripts with TTL-based expiration
 */
export class SqliteTranscriptRepository implements TranscriptRepositoryPort {
  private db: Database.Database | null = null;
  private readonly config: CacheConfig;
  private readonly logger: {
    debug: (msg: string, meta?: Record<string, unknown>) => void;
    error: (msg: string, meta?: Record<string, unknown>) => void;
  };

  constructor(
    config: CacheConfig,
    logger: {
      debug: (msg: string, meta?: Record<string, unknown>) => void;
      error: (msg: string, meta?: Record<string, unknown>) => void;
    }
  ) {
    this.config = config;
    this.logger = logger;
  }

  /**
   * Initialize database connection and schema
   */
  async initialize(): Promise<void> {
    if (this.db) return;

    const dbPath = resolve(this.config.sqlitePath);
    mkdirSync(dirname(dbPath), { recursive: true });

    this.db = new Database(dbPath);
    this.db.pragma('journal_mode = WAL');
    this.db.pragma('busy_timeout = 5000');

    // Create transcripts table
    this.db.exec(`
      CREATE TABLE IF NOT EXISTS transcripts (
        id TEXT PRIMARY KEY,
        video_id TEXT NOT NULL,
        language TEXT NOT NULL,
        source TEXT NOT NULL,
        segments TEXT NOT NULL,
        fetched_at TEXT NOT NULL,
        is_auto_generated INTEGER NOT NULL DEFAULT 0,
        expires_at INTEGER NOT NULL,
        created_at INTEGER NOT NULL DEFAULT (strftime('%s', 'now'))
      );

      CREATE INDEX IF NOT EXISTS idx_transcripts_video_lang ON transcripts(video_id, language);
      CREATE INDEX IF NOT EXISTS idx_transcripts_expires ON transcripts(expires_at);
    `);

    // Create cache metadata table
    this.db.exec(`
      CREATE TABLE IF NOT EXISTS cache_meta (
        key TEXT PRIMARY KEY,
        value TEXT NOT NULL
      );
    `);

    if (this.config.vacuumOnStartup) {
      this.db.exec('VACUUM');
    }

    this.logger.debug('SQLite transcript repository initialized', { path: dbPath });

    // Start cleanup interval
    this.startCleanupInterval();
  }

  /**
   * Close database connection
   */
  async close(): Promise<void> {
    if (this.db) {
      this.db.close();
      this.db = null;
      this.logger.debug('SQLite transcript repository closed');
    }
  }

  /**
   * Ensure database is initialized
   */
  private ensureDb(): Database.Database {
    if (!this.db) {
      throw new AppError(
        ErrorCodes.CACHE_CONNECTION_FAILED,
        'Database not initialized. Call initialize() first.'
      );
    }
    return this.db;
  }

  /**
   * Get transcript from cache
   */
  async get(
    videoId: VideoId,
    language: LanguageCode
  ): Promise<Result<Transcript | null, AppError>> {
    try {
      const db = this.ensureDb();
      const now = Date.now();

      const row = db
        .prepare(
          `
        SELECT * FROM transcripts
        WHERE video_id = ? AND language = ? AND expires_at > ?
      `
        )
        .get(videoId.value, language.code, now) as
        | {
            id: string;
            video_id: string;
            language: string;
            source: string;
            segments: string;
            fetched_at: string;
            is_auto_generated: number;
            expires_at: number;
          }
        | undefined;

      if (!row) {
        return ok(null);
      }

      const transcriptResult = Transcript.reconstruct({
        id: row.id,
        videoId: row.video_id,
        language: row.language,
        source: row.source as Transcript['source'],
        segments: JSON.parse(row.segments),
        fetchedAt: row.fetched_at,
        isAutoGenerated: Boolean(row.is_auto_generated),
      });

      if (!transcriptResult.ok) {
        this.logger.error('Failed to reconstruct transcript from cache', {
          videoId: videoId.value,
          language: language.code,
          error: transcriptResult.error.message,
        });
        // Corrupted cache entry - delete it
        await this.delete(videoId, language);
        return err(transcriptResult.error);
      }

      return ok(transcriptResult.value);
    } catch (error) {
      return err(
        new AppError(ErrorCodes.CACHE_READ_FAILED, 'Failed to read transcript from cache', {
          cause: error instanceof Error ? error : undefined,
          context: { videoId: videoId.value, language: language.code },
        })
      );
    }
  }

  /**
   * Store transcript in cache
   */
  async set(transcript: Transcript, ttlSeconds?: number): Promise<Result<void, AppError>> {
    try {
      const db = this.ensureDb();
      const ttl = ttlSeconds ?? this.config.ttlSeconds;
      const expiresAt = Date.now() + ttl * 1000;
      const data = transcript.toJSON();

      db.prepare(
        `
        INSERT OR REPLACE INTO transcripts (id, video_id, language, source, segments, fetched_at, is_auto_generated, expires_at)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?)
      `
      ).run(
        data.id,
        data.videoId,
        data.language,
        data.source,
        JSON.stringify(data.segments),
        data.fetchedAt,
        data.isAutoGenerated ? 1 : 0,
        expiresAt
      );

      this.logger.debug('Transcript cached', {
        videoId: transcript.videoId.value,
        language: transcript.language.code,
        ttlSeconds: ttl,
      });

      return ok(undefined);
    } catch (error) {
      return err(
        new AppError(ErrorCodes.CACHE_WRITE_FAILED, 'Failed to write transcript to cache', {
          cause: error instanceof Error ? error : undefined,
          context: { videoId: transcript.videoId.value, language: transcript.language.code },
        })
      );
    }
  }

  /**
   * Check if transcript exists in cache
   */
  async has(videoId: VideoId, language: LanguageCode): Promise<Result<boolean, AppError>> {
    try {
      const db = this.ensureDb();
      const now = Date.now();

      const count = db
        .prepare(
          `
        SELECT COUNT(*) as count FROM transcripts
        WHERE video_id = ? AND language = ? AND expires_at > ?
      `
        )
        .get(videoId.value, language.code, now) as { count: number };

      return ok(count.count > 0);
    } catch (error) {
      return err(
        new AppError(ErrorCodes.CACHE_READ_FAILED, 'Failed to check cache', {
          cause: error instanceof Error ? error : undefined,
          context: { videoId: videoId.value, language: language.code },
        })
      );
    }
  }

  /**
   * Delete transcript from cache
   */
  async delete(videoId: VideoId, language: LanguageCode): Promise<Result<boolean, AppError>> {
    try {
      const db = this.ensureDb();

      const result = db
        .prepare(
          `
        DELETE FROM transcripts WHERE video_id = ? AND language = ?
      `
        )
        .run(videoId.value, language.code);

      return ok(result.changes > 0);
    } catch (error) {
      return err(
        new AppError(ErrorCodes.CACHE_WRITE_FAILED, 'Failed to delete transcript from cache', {
          cause: error instanceof Error ? error : undefined,
          context: { videoId: videoId.value, language: language.code },
        })
      );
    }
  }

  /**
   * Clear all transcripts from cache
   */
  async clear(): Promise<Result<void, AppError>> {
    try {
      const db = this.ensureDb();
      db.prepare('DELETE FROM transcripts').run();
      return ok(undefined);
    } catch (error) {
      return err(
        new AppError(ErrorCodes.CACHE_WRITE_FAILED, 'Failed to clear cache', {
          cause: error instanceof Error ? error : undefined,
        })
      );
    }
  }

  /**
   * Get all cached transcript keys
   */
  async keys(): Promise<Result<string[], AppError>> {
    try {
      const db = this.ensureDb();
      const now = Date.now();

      const rows = db
        .prepare(
          `
        SELECT video_id, language FROM transcripts WHERE expires_at > ?
      `
        )
        .all(now) as { video_id: string; language: string }[];

      return ok(rows.map((r) => `${r.video_id}:${r.language}`));
    } catch (error) {
      return err(
        new AppError(ErrorCodes.CACHE_READ_FAILED, 'Failed to get cache keys', {
          cause: error instanceof Error ? error : undefined,
        })
      );
    }
  }

  /**
   * Get cache statistics
   */
  async stats(): Promise<Result<{ count: number; sizeBytes: number }, AppError>> {
    try {
      const db = this.ensureDb();
      const now = Date.now();

      const countRow = db
        .prepare(
          `
        SELECT COUNT(*) as count FROM transcripts WHERE expires_at > ?
      `
        )
        .get(now) as { count: number };

      const sizeRow = db
        .prepare(
          `
        SELECT SUM(LENGTH(segments)) as size FROM transcripts WHERE expires_at > ?
      `
        )
        .get(now) as { size: number | null };

      return ok({
        count: countRow.count,
        sizeBytes: sizeRow.size ?? 0,
      });
    } catch (error) {
      return err(
        new AppError(ErrorCodes.CACHE_READ_FAILED, 'Failed to get cache stats', {
          cause: error instanceof Error ? error : undefined,
        })
      );
    }
  }

  /**
   * Health check
   */
  async healthCheck(): Promise<
    Result<{ healthy: boolean; details?: Record<string, unknown> }, AppError>
  > {
    try {
      if (!this.db) {
        return ok({ healthy: false, details: { reason: 'Not initialized' } });
      }

      this.db.prepare('SELECT 1').get();
      const stats = await this.stats();

      return ok({
        healthy: true,
        details: {
          type: 'sqlite',
          path: this.config.sqlitePath,
          ...(stats.ok ? stats.value : {}),
        },
      });
    } catch (error) {
      return ok({
        healthy: false,
        details: { error: error instanceof Error ? error.message : String(error) },
      });
    }
  }

  /**
   * Start periodic cleanup of expired entries
   */
  private startCleanupInterval(): void {
    if (this.config.cleanupIntervalMs <= 0) return;

    setInterval(async () => {
      try {
        const db = this.ensureDb();
        const now = Date.now();
        const result = db.prepare('DELETE FROM transcripts WHERE expires_at <= ?').run(now);
        if (result.changes > 0) {
          this.logger.debug('Cleaned up expired transcripts', { deleted: result.changes });
        }
      } catch (error) {
        this.logger.error('Cache cleanup failed', {
          error: error instanceof Error ? error.message : String(error),
        });
      }
    }, this.config.cleanupIntervalMs);
  }
}
