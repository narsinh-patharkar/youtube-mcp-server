/**
 * YoutubeTranscriptApiAdapter - Primary transcript extractor using youtube-transcript npm package
 */

import { AppError, ErrorCodes, isAppError, TranscriptError } from '@core/errors/index.js';
import { withRetry, withTimeout } from '@core/utils/async.js';
import type { Result } from '@core/utils/result.js';
import { combine, err, ok, tryAsync } from '@core/utils/result.js';
import { LanguageCode } from '@domain/transcript/language-code.js';
import type {
  AvailableLanguages,
  TranscriptExtractorConfig,
  TranscriptExtractorPort,
} from '@domain/transcript/ports/transcript-extractor.port.js';
import { TranscriptSegment } from '@domain/transcript/transcript-segment.js';
import { Transcript } from '@domain/transcript/transcript.js';
import { VideoId } from '@domain/transcript/video-id.js';
import { YoutubeTranscript } from 'youtube-transcript';

/**
 * Adapter for youtube-transcript-api (fast, no external dependencies)
 * Priority: 1 (highest - tried first)
 */
export class YoutubeTranscriptApiAdapter implements TranscriptExtractorPort {
  readonly name = 'youtube-transcript-api';
  readonly priority = 1;

  private readonly config: TranscriptExtractorConfig;

  constructor(config: TranscriptExtractorConfig) {
    this.config = config;
  }

  /**
   * Extract transcript using youtube-transcript package
   */
  async extract(videoId: VideoId, language?: LanguageCode): Promise<Result<Transcript, AppError>> {
    const targetLang = language?.code ?? this.config.defaultLanguage;

    return tryAsync(async () => {
      // Use withTimeout and withRetry for resilience
      const transcriptData = await withTimeout(
        withRetry(() => YoutubeTranscript.fetchTranscript(videoId.value, { lang: targetLang }), {
          maxAttempts: this.config.maxRetries + 1,
          baseDelayMs: 1000,
          maxDelayMs: 10000,
          shouldRetry: (error: Error) => this.isRetryableError(error),
        }),
        this.config.timeoutMs,
        new AppError(
          ErrorCodes.TRANSCRIPT_FETCH_FAILED,
          `Transcript fetch timeout after ${this.config.timeoutMs}ms`
        )
      );

      if (!transcriptData || transcriptData.length === 0) {
        throw new AppError(ErrorCodes.TRANSCRIPT_EMPTY, 'No transcript found', {
          context: { videoId: videoId.value, language: targetLang },
        });
      }

      // Convert API response to TranscriptSegments
      const segmentsResult = combine(
        transcriptData.map((item) => TranscriptSegment.fromApiResponse(item))
      );

      if (!segmentsResult.ok) {
        throw segmentsResult.error;
      }

      // Detect if auto-generated (youtube-transcript doesn't explicitly tell us)
      // We'll infer from the response or assume false
      const isAutoGenerated = false; // youtube-transcript typically returns manual captions

      // Create transcript entity
      const transcriptResult = Transcript.create(
        videoId,
        LanguageCode.createUnsafe(targetLang),
        this.name as TranscriptExtractorPort['name'] extends TranscriptExtractorPort['name']
          ? 'youtube-transcript-api'
          : 'youtube-transcript-api',
        segmentsResult.value,
        { isAutoGenerated }
      );

      if (!transcriptResult.ok) {
        throw transcriptResult.error;
      }

      return transcriptResult.value;
    });
  }

  /**
   * Get available languages for a video
   */
  async getAvailableLanguages(videoId: VideoId): Promise<Result<AvailableLanguages[], AppError>> {
    return tryAsync(async () => {
      // youtube-transcript doesn't have a direct API for getting available languages
      // We'll try to fetch with a common language to see what's available
      // This is a limitation - we return empty array and let fallback handle it
      return [] as AvailableLanguages[];
    });
  }

  /**
   * Health check
   */
  async isHealthy(): Promise<Result<boolean, AppError>> {
    return tryAsync(async () => {
      // Simple check - try to import the module
      await import('youtube-transcript');
      return true;
    });
  }

  /**
   * Check if error is retryable
   */
  private isRetryableError(error: Error): boolean {
    if (isAppError(error)) {
      return error.isRetryable;
    }
    // Network errors, timeouts, etc. are retryable
    const retryablePatterns = [
      /timeout/i,
      /network/i,
      /ECONNREFUSED/,
      /ENOTFOUND/,
      /ETIMEDOUT/,
      /socket hang up/i,
    ];
    return retryablePatterns.some((pattern) => pattern.test(error.message));
  }
}
