/**
 * YtDlpAdapter - Fallback transcript extractor using yt-dlp CLI
 * More robust, handles age-restricted, geo-blocked, and private videos
 */

import { AppError, ErrorCodes, isAppError } from '@core/errors/index.js';
import { withTimeout } from '@core/utils/async.js';
import type { Result } from '@core/utils/result.js';
import { combine, err, ok, tryAsync } from '@core/utils/result.js';
import { LanguageCode } from '@domain/transcript/language-code.js';
import type {
  AvailableLanguages,
  TranscriptExtractorConfig,
  TranscriptExtractorPort,
} from '@domain/transcript/ports/transcript-extractor.port.js';
import { TranscriptSegment } from '@domain/transcript/transcript-segment.js';
import { Transcript } from '@domain/transcript/transcript.js';
import { VideoId } from '@domain/transcript/video-id.js';
import { spawn } from 'node:child_process';

/**
 * yt-dlp JSON output structure for subtitles
 */
interface YtDlpSubtitle {
  text: string;
  start: number;
  duration: number;
}

interface YtDlpInfo {
  id: string;
  title: string;
  subtitles?: Record<string, YtDlpSubtitle[]>;
  automatic_captions?: Record<string, YtDlpSubtitle[]>;
}

/**
 * Adapter for yt-dlp (robust, handles edge cases)
 * Priority: 10 (lower priority - tried after youtube-transcript-api)
 */
export class YtDlpAdapter implements TranscriptExtractorPort {
  readonly name = 'yt-dlp';
  readonly priority = 10;

  private readonly config: TranscriptExtractorConfig;
  private readonly ytDlpPath: string;

  constructor(config: TranscriptExtractorConfig, ytDlpPath?: string) {
    this.config = config;
    this.ytDlpPath = ytDlpPath ?? 'yt-dlp';
  }

  /**
   * Extract transcript using yt-dlp
   */
  async extract(videoId: VideoId, language?: LanguageCode): Promise<Result<Transcript, AppError>> {
    const targetLang = language?.code ?? this.config.defaultLanguage;

    return tryAsync(async () => {
      // Get video info with subtitles
      const info = await this.getVideoInfo(videoId.value);
      if (!info) {
        throw new AppError(ErrorCodes.VIDEO_NOT_FOUND, 'Video not found', {
          context: { videoId: videoId.value },
        });
      }

      // Find best matching subtitle track
      const subtitleTrack = this.findBestSubtitleTrack(info, targetLang);
      if (!subtitleTrack) {
        throw new AppError(
          ErrorCodes.TRANSCRIPT_LANGUAGE_UNAVAILABLE,
          'No transcript available in requested language',
          {
            context: {
              videoId: videoId.value,
              requestedLanguage: targetLang,
              available: this.getAvailableLanguagesFromInfo(info),
            },
          }
        );
      }

      // Convert to segments
      const segmentsResult = combine(
        subtitleTrack.map((item) => TranscriptSegment.fromYtDlpResponse(item))
      );

      if (!segmentsResult.ok) {
        throw segmentsResult.error;
      }

      // Check if auto-generated
      const isAutoGenerated = this.isAutoGeneratedTrack(info, subtitleTrack);

      // Create transcript
      const transcriptResult = Transcript.create(
        videoId,
        LanguageCode.createUnsafe(targetLang),
        'yt-dlp',
        segmentsResult.value,
        { isAutoGenerated }
      );

      if (!transcriptResult.ok) {
        throw transcriptResult.error;
      }

      return transcriptResult.value;
    });
  }

  /**
   * Get available languages for a video
   */
  async getAvailableLanguages(videoId: VideoId): Promise<Result<AvailableLanguages[], AppError>> {
    return tryAsync(async () => {
      const info = await this.getVideoInfo(videoId.value);
      if (!info) {
        return [];
      }

      const languages: AvailableLanguages[] = [];

      // Manual subtitles
      if (info.subtitles) {
        for (const [lang, tracks] of Object.entries(info.subtitles)) {
          languages.push({
            code: lang,
            name: this.getLanguageName(lang),
            isAutoGenerated: false,
            isTranslation: false,
          });
        }
      }

      // Auto-generated captions
      if (info.automatic_captions) {
        for (const [lang, tracks] of Object.entries(info.automatic_captions)) {
          languages.push({
            code: lang,
            name: this.getLanguageName(lang),
            isAutoGenerated: true,
            isTranslation: false,
          });
        }
      }

      return languages;
    });
  }

  /**
   * Health check - verify yt-dlp is available
   */
  async isHealthy(): Promise<Result<boolean, AppError>> {
    return tryAsync(async () => {
      return new Promise<boolean>((resolve) => {
        const proc = spawn(this.ytDlpPath, ['--version'], { stdio: 'pipe' });
        proc.on('close', (code) => resolve(code === 0));
        proc.on('error', () => resolve(false));
        // Timeout after 5 seconds
        setTimeout(() => {
          proc.kill();
          resolve(false);
        }, 5000);
      });
    });
  }

  /**
   * Get video info with subtitles using yt-dlp
   */
  private async getVideoInfo(videoId: string): Promise<YtDlpInfo | null> {
    return new Promise<YtDlpInfo | null>((resolve, reject) => {
      const url = `https://www.youtube.com/watch?v=${videoId}`;
      const args = [
        '--skip-download',
        '--write-auto-subs',
        '--write-subs',
        '--sub-format',
        'json3',
        '--print-json',
        url,
      ];

      const proc = spawn(this.ytDlpPath, args, { stdio: ['ignore', 'pipe', 'pipe'] });
      let stdout = '';
      let stderr = '';

      proc.stdout.on('data', (data) => {
        stdout += data.toString();
      });
      proc.stderr.on('data', (data) => {
        stderr += data.toString();
      });

      const timeout = setTimeout(() => {
        proc.kill('SIGTERM');
        reject(new Error('yt-dlp timeout'));
      }, this.config.timeoutMs);

      proc.on('close', (code) => {
        clearTimeout(timeout);
        if (code !== 0) {
          // Check for specific error patterns
          if (stderr.includes('Video unavailable') || stderr.includes('Private video')) {
            resolve(null);
            return;
          }
          reject(new Error(`yt-dlp exited with code ${code}: ${stderr}`));
          return;
        }

        try {
          // yt-dlp outputs JSON on the last line of stdout
          const lines = stdout.trim().split('\n');
          const jsonLine = lines[lines.length - 1];
          const info = JSON.parse(jsonLine) as YtDlpInfo;
          resolve(info);
        } catch (e) {
          reject(new Error(`Failed to parse yt-dlp output: ${e}`));
        }
      });

      proc.on('error', (error) => {
        clearTimeout(timeout);
        reject(error);
      });
    });
  }

  /**
   * Find best matching subtitle track
   */
  private findBestSubtitleTrack(info: YtDlpInfo, targetLang: string): YtDlpSubtitle[] | null {
    const normalizedTarget = targetLang.toLowerCase();

    // 1. Try exact match in manual subtitles
    if (info.subtitles?.[normalizedTarget]) {
      return info.subtitles[normalizedTarget];
    }

    // 2. Try exact match in auto captions
    if (info.automatic_captions?.[normalizedTarget]) {
      return info.automatic_captions[normalizedTarget];
    }

    // 3. Try base language match (e.g., 'en' for 'en-US')
    const baseTarget = normalizedTarget.split('-')[0];
    for (const [lang, tracks] of Object.entries(info.subtitles ?? {})) {
      if (lang.startsWith(baseTarget)) return tracks;
    }
    for (const [lang, tracks] of Object.entries(info.automatic_captions ?? {})) {
      if (lang.startsWith(baseTarget)) return tracks;
    }

    // 4. Try any English variant
    if (baseTarget !== 'en') {
      for (const [lang, tracks] of Object.entries(info.subtitles ?? {})) {
        if (lang.startsWith('en')) return tracks;
      }
      for (const [lang, tracks] of Object.entries(info.automatic_captions ?? {})) {
        if (lang.startsWith('en')) return tracks;
      }
    }

    // 5. Return first available
    const firstManual = Object.values(info.subtitles ?? {})[0];
    if (firstManual) return firstManual;
    const firstAuto = Object.values(info.automatic_captions ?? {})[0];
    if (firstAuto) return firstAuto;

    return null;
  }

  /**
   * Check if track is auto-generated
   */
  private isAutoGeneratedTrack(info: YtDlpInfo, track: YtDlpSubtitle[]): boolean {
    // Check if this track exists in automatic_captions
    for (const autoTrack of Object.values(info.automatic_captions ?? {})) {
      if (autoTrack === track) return true;
      // Compare by content (first few items)
      if (
        autoTrack.length > 0 &&
        track.length > 0 &&
        autoTrack[0].text === track[0].text &&
        autoTrack[0].start === track[0].start
      ) {
        return true;
      }
    }
    return false;
  }

  /**
   * Get available language codes from info
   */
  private getAvailableLanguagesFromInfo(info: YtDlpInfo): string[] {
    return [...Object.keys(info.subtitles ?? {}), ...Object.keys(info.automatic_captions ?? {})];
  }

  /**
   * Get human-readable language name
   */
  private getLanguageName(code: string): string {
    const names: Record<string, string> = {
      en: 'English',
      es: 'Spanish',
      fr: 'French',
      de: 'German',
      it: 'Italian',
      pt: 'Portuguese',
      ru: 'Russian',
      ja: 'Japanese',
      ko: 'Korean',
      zh: 'Chinese',
      ar: 'Arabic',
      hi: 'Hindi',
    };
    return names[code.toLowerCase().split('-')[0]] ?? code;
  }
}
