/**
 * GetTranscriptUseCase - Application use case for fetching transcripts
 */

import { AppError } from '@core/errors/index.js';
import type { Result } from '@core/utils/result.js';
import { err, ok } from '@core/utils/result.js';
import { LanguageCode } from '@domain/transcript/language-code.js';
import { Transcript } from '@domain/transcript/transcript.js';
import { VideoId } from '@domain/transcript/video-id.js';
import type { GetTranscriptInput, GetTranscriptOutput } from '../dto/transcript.dto.js';
import { parseGetTranscriptInput } from '../dto/transcript.dto.js';
import { TranscriptService } from '../services/transcript.service.js';

/**
 * GetTranscriptUseCase dependencies
 */
export interface GetTranscriptUseCaseDeps {
  transcriptService: TranscriptService;
  logger: {
    debug: (msg: string, meta?: Record<string, unknown>) => void;
    info: (msg: string, meta?: Record<string, unknown>) => void;
    warn: (msg: string, meta?: Record<string, unknown>) => void;
    error: (msg: string, meta?: Record<string, unknown>) => void;
  };
}

/**
 * Use case for getting a transcript
 * Handles input validation, orchestration, and output formatting
 */
export class GetTranscriptUseCase {
  private readonly transcriptService: TranscriptService;
  private readonly logger: GetTranscriptUseCaseDeps['logger'];

  constructor(deps: GetTranscriptUseCaseDeps) {
    this.transcriptService = deps.transcriptService;
    this.logger = deps.logger;
  }

  /**
   * Execute the use case
   */
  async execute(input: GetTranscriptInput): Promise<Result<GetTranscriptOutput, AppError>> {
    // Parse and validate input
    const parsedResult = parseGetTranscriptInput(input);
    if (!parsedResult.ok) {
      return err(parsedResult.error);
    }

    const { videoId, language, forceRefresh } = parsedResult.value;

    this.logger.debug('Executing GetTranscriptUseCase', {
      videoId: videoId.value,
      language: language?.code,
      forceRefresh,
    });

    // Delegate to service
    const result = await this.transcriptService.getTranscript(videoId, language, forceRefresh);

    if (!result.ok) {
      this.logger.warn('GetTranscriptUseCase failed', {
        videoId: videoId.value,
        language: language?.code,
        error: result.error.code,
        message: result.error.message,
      });
      return err(result.error);
    }

    this.logger.info('GetTranscriptUseCase completed', {
      videoId: videoId.value,
      language: result.value.transcript.language.code,
      fromCache: result.value.fromCache,
      segmentCount: result.value.transcript.segmentCount,
    });

    return ok({
      transcript: result.value.transcript,
      fromCache: result.value.fromCache,
    });
  }

  /**
   * Get available languages for a video
   */
  async getAvailableLanguages(videoIdOrUrl: string): Promise<
    Result<
      Array<{
        code: string;
        name: string;
        isAutoGenerated: boolean;
        isTranslation: boolean;
      }>,
      AppError
    >
  > {
    const videoIdResult = VideoId.fromUrlOrId(videoIdOrUrl);
    if (!videoIdResult.ok) {
      return err(videoIdResult.error);
    }

    return this.transcriptService.getAvailableLanguages(videoIdResult.value);
  }
}
