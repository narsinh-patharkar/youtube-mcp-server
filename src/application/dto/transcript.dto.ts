/**
 * Transcript DTOs - Input/Output data transfer objects
 */

import { AppError, ErrorCodes } from '@core/errors/index.js';
import type { Result } from '@core/utils/result.js';
import { err, ok } from '@core/utils/result.js';
import { LanguageCode } from '@domain/transcript/language-code.js';
import { Transcript } from '@domain/transcript/transcript.js';
import { VideoId } from '@domain/transcript/video-id.js';
import { z } from 'zod';

/**
 * Input for getting a transcript
 */
export const GetTranscriptInputSchema = z.object({
  /** Video ID or URL */
  videoIdOrUrl: z.string().min(1),
  /** Preferred language code (ISO 639-1) */
  language: z
    .string()
    .regex(/^[a-z]{2}(-[A-Z]{2,4})?$/i)
    .optional(),
  /** Force refresh (bypass cache) */
  forceRefresh: z.boolean().default(false),
});

export type GetTranscriptInput = z.infer<typeof GetTranscriptInputSchema>;

/**
 * Parsed and validated input
 */
export interface ParsedGetTranscriptInput {
  videoId: VideoId;
  language?: LanguageCode;
  forceRefresh: boolean;
}

/**
 * Parse and validate GetTranscriptInput
 */
export function parseGetTranscriptInput(
  input: GetTranscriptInput
): Result<ParsedGetTranscriptInput, AppError> {
  const result = GetTranscriptInputSchema.safeParse(input);
  if (!result.success) {
    return err(
      new AppError(ErrorCodes.MCP_INVALID_ARGUMENTS, 'Invalid input', {
        context: { issues: result.error.issues },
      })
    );
  }

  const videoIdResult = VideoId.fromUrlOrId(result.data.videoIdOrUrl);
  if (!videoIdResult.ok) {
    return err(videoIdResult.error);
  }

  let language: LanguageCode | undefined;
  if (result.data.language) {
    const langResult = LanguageCode.create(result.data.language);
    if (!langResult.ok) {
      return err(langResult.error);
    }
    language = langResult.value;
  }

  return ok({
    videoId: videoIdResult.value,
    language,
    forceRefresh: result.data.forceRefresh,
  });
}

/**
 * Output from getting a transcript
 */
export interface GetTranscriptOutput {
  /** The transcript */
  transcript: Transcript;
  /** Whether the transcript was retrieved from cache */
  fromCache: boolean;
}

/**
 * Transcript summary for listings
 */
export interface TranscriptSummary {
  videoId: string;
  language: string;
  source: string;
  segmentCount: number;
  duration: number;
  wordCount: number;
  fetchedAt: string;
  isAutoGenerated: boolean;
}

/**
 * Convert Transcript to summary
 */
export function toTranscriptSummary(transcript: Transcript): TranscriptSummary {
  return {
    videoId: transcript.videoId.value,
    language: transcript.language.code,
    source: transcript.source,
    segmentCount: transcript.segmentCount,
    duration: transcript.duration,
    wordCount: transcript.wordCount,
    fetchedAt: transcript.fetchedAt.toISOString(),
    isAutoGenerated: transcript.isAutoGenerated,
  };
}

/**
 * Available languages output
 */
export interface AvailableLanguagesOutput {
  videoId: string;
  languages: Array<{
    code: string;
    name: string;
    isAutoGenerated: boolean;
    isTranslation: boolean;
  }>;
}
