/**
 * Transcript Entity - Full transcript with metadata and segments
 */

import { AppError, ErrorCodes } from '@core/errors/index.js';
import { generateId } from '@core/utils/crypto.js';
import type { Result } from '@core/utils/result.js';
import { combine, err, ok } from '@core/utils/result.js';
import { z } from 'zod';
import { LanguageCode } from './language-code.js';
import { TranscriptSegment } from './transcript-segment.js';
import { VideoId } from './video-id.js';

/**
 * Transcript source types
 */
export type TranscriptSource = 'youtube-transcript-api' | 'yt-dlp' | 'manual';

/**
 * Transcript schema for validation
 */
export const TranscriptSchema = z.object({
  id: z.string().uuid(),
  videoId: z.string().regex(/^[a-zA-Z0-9_-]{11}$/),
  language: z.string().regex(/^[a-z]{2}(-[A-Z]{2,4})?$/i),
  source: z.enum(['youtube-transcript-api', 'yt-dlp', 'manual']),
  segments: z.array(
    z.object({
      text: z.string().min(1),
      start: z.number().int().nonnegative(),
      duration: z.number().int().positive(),
    })
  ),
  fetchedAt: z.string().datetime(),
  isAutoGenerated: z.boolean().default(false),
});

/**
 * Transcript entity - represents a complete video transcript
 */
export class Transcript {
  private readonly _id: string;
  private readonly _videoId: VideoId;
  private readonly _language: LanguageCode;
  private readonly _source: TranscriptSource;
  private readonly _segments: readonly TranscriptSegment[];
  private readonly _fetchedAt: Date;
  private readonly _isAutoGenerated: boolean;
  private readonly _fullText: string;

  private constructor(
    id: string,
    videoId: VideoId,
    language: LanguageCode,
    source: TranscriptSource,
    segments: TranscriptSegment[],
    fetchedAt: Date,
    isAutoGenerated: boolean = false
  ) {
    this._id = id;
    this._videoId = videoId;
    this._language = language;
    this._source = source;
    this._segments = Object.freeze([...segments].sort((a, b) => a.start - b.start));
    this._fetchedAt = fetchedAt;
    this._isAutoGenerated = isAutoGenerated;
    this._fullText = this._segments.map((s) => s.text).join(' ');
  }

  /**
   * Create a new Transcript
   */
  static create(
    videoId: VideoId,
    language: LanguageCode,
    source: TranscriptSource,
    segments: TranscriptSegment[],
    options?: { fetchedAt?: Date; isAutoGenerated?: boolean; id?: string }
  ): Result<Transcript, AppError> {
    if (segments.length === 0) {
      return err(new AppError(ErrorCodes.TRANSCRIPT_EMPTY, 'Transcript cannot be empty'));
    }

    // Validate segments are in order and don't overlap
    const sortedSegments = [...segments].sort((a, b) => a.start - b.start);
    for (let i = 1; i < sortedSegments.length; i++) {
      if (sortedSegments[i].start < sortedSegments[i - 1].end) {
        return err(
          new AppError(ErrorCodes.TRANSCRIPT_PARSE_FAILED, 'Transcript segments overlap', {
            context: {
              segmentIndex: i,
              prevEnd: sortedSegments[i - 1].end,
              currStart: sortedSegments[i].start,
            },
          })
        );
      }
    }

    const id = options?.id ?? generateId();
    const fetchedAt = options?.fetchedAt ?? new Date();
    const isAutoGenerated = options?.isAutoGenerated ?? false;

    return ok(
      new Transcript(id, videoId, language, source, sortedSegments, fetchedAt, isAutoGenerated)
    );
  }

  /**
   * Reconstruct Transcript from stored data (e.g., database)
   * @internal Use with caution - bypasses validation
   */
  static reconstruct(data: {
    id: string;
    videoId: string;
    language: string;
    source: TranscriptSource;
    segments: { text: string; start: number; duration: number }[];
    fetchedAt: string | Date;
    isAutoGenerated: boolean;
  }): Result<Transcript, AppError> {
    const videoIdResult = VideoId.create(data.videoId);
    if (!videoIdResult.ok) return err(videoIdResult.error);

    const languageResult = LanguageCode.create(data.language);
    if (!languageResult.ok) return err(languageResult.error);

    const segmentsResult = combine(
      data.segments.map((s) => TranscriptSegment.create(s.text, s.start, s.duration))
    );
    if (!segmentsResult.ok) return err(segmentsResult.error);

    const fetchedAt =
      typeof data.fetchedAt === 'string' ? new Date(data.fetchedAt) : data.fetchedAt;

    return Transcript.create(
      videoIdResult.value,
      languageResult.value,
      data.source,
      segmentsResult.value,
      { fetchedAt, isAutoGenerated: data.isAutoGenerated, id: data.id }
    );
  }

  /**
   * Get unique identifier
   */
  get id(): string {
    return this._id;
  }

  /**
   * Get video ID
   */
  get videoId(): VideoId {
    return this._videoId;
  }

  /**
   * Get language
   */
  get language(): LanguageCode {
    return this._language;
  }

  /**
   * Get source
   */
  get source(): TranscriptSource {
    return this._source;
  }

  /**
   * Get all segments (read-only)
   */
  get segments(): readonly TranscriptSegment[] {
    return this._segments;
  }

  /**
   * Get segment count
   */
  get segmentCount(): number {
    return this._segments.length;
  }

  /**
   * Get full transcript text
   */
  get fullText(): string {
    return this._fullText;
  }

  /**
   * Get full text word count
   */
  get wordCount(): number {
    return this._fullText.split(/\s+/).filter((w) => w.length > 0).length;
  }

  /**
   * Get character count
   */
  get charCount(): number {
    return this._fullText.length;
  }

  /**
   * Get fetch timestamp
   */
  get fetchedAt(): Date {
    return this._fetchedAt;
  }

  /**
   * Check if auto-generated (YouTube's automatic captions)
   */
  get isAutoGenerated(): boolean {
    return this._isAutoGenerated;
  }

  /**
   * Get transcript duration in seconds
   */
  get duration(): number {
    if (this._segments.length === 0) return 0;
    const lastSegment = this._segments[this._segments.length - 1];
    return lastSegment.end;
  }

  /**
   * Get duration formatted as HH:MM:SS
   */
  get durationFormatted(): string {
    const secs = Math.floor(this.duration);
    const hrs = Math.floor(secs / 3600);
    const mins = Math.floor((secs % 3600) / 60);
    const remainingSecs = secs % 60;
    if (hrs > 0) {
      return `${hrs.toString().padStart(2, '0')}:${mins.toString().padStart(2, '0')}:${remainingSecs.toString().padStart(2, '0')}`;
    }
    return `${mins.toString().padStart(2, '0')}:${remainingSecs.toString().padStart(2, '0')}`;
  }

  /**
   * Get segment at specific time (in seconds)
   */
  getSegmentAt(timeSeconds: number): TranscriptSegment | undefined {
    return this._segments.find((s) => s.start <= timeSeconds && timeSeconds < s.end);
  }

  /**
   * Get segments within time range (overlapping)
   */
  getSegmentsInRange(startSeconds: number, endSeconds: number): TranscriptSegment[] {
    return this._segments.filter((s) => s.start < endSeconds && s.end > startSeconds);
  }

  /**
   * Get text within time range
   */
  getTextInRange(startSeconds: number, endSeconds: number): string {
    return this.getSegmentsInRange(startSeconds, endSeconds)
      .map((s) => s.text)
      .join(' ');
  }

  /**
   * Split transcript into chunks by token count (approximate)
   */
  chunkByTokens(maxTokensPerChunk: number, overlapTokens: number = 0): Transcript[] {
    // Rough approximation: 1 token ≈ 4 characters
    const maxCharsPerChunk = maxTokensPerChunk * 4;
    const overlapChars = overlapTokens * 4;

    const chunks: Transcript[] = [];
    let currentSegments: TranscriptSegment[] = [];
    let currentChars = 0;

    for (const segment of this._segments) {
      const segmentChars = segment.text.length + 1; // +1 for space

      if (currentChars + segmentChars > maxCharsPerChunk && currentSegments.length > 0) {
        // Create chunk from current segments
        const chunkResult = Transcript.create(
          this._videoId,
          this._language,
          this._source,
          currentSegments,
          { fetchedAt: this._fetchedAt, isAutoGenerated: this._isAutoGenerated }
        );
        if (chunkResult.ok) {
          chunks.push(chunkResult.value);
        }

        // Start new chunk with overlap
        if (overlapChars > 0 && chunks.length > 0) {
          // Find segments to overlap
          let overlapCharCount = 0;
          const overlapSegments: TranscriptSegment[] = [];
          for (let i = currentSegments.length - 1; i >= 0; i--) {
            const segChars = currentSegments[i].text.length + 1;
            if (overlapCharCount + segChars > overlapChars) break;
            overlapSegments.unshift(currentSegments[i]);
            overlapCharCount += segChars;
          }
          currentSegments = [...overlapSegments];
          currentChars = overlapCharCount;
        } else {
          currentSegments = [];
          currentChars = 0;
        }
      }

      currentSegments.push(segment);
      currentChars += segmentChars;
    }

    // Add remaining segments as final chunk
    if (currentSegments.length > 0) {
      const chunkResult = Transcript.create(
        this._videoId,
        this._language,
        this._source,
        currentSegments,
        { fetchedAt: this._fetchedAt, isAutoGenerated: this._isAutoGenerated }
      );
      if (chunkResult.ok) {
        chunks.push(chunkResult.value);
      }
    }

    return chunks;
  }

  /**
   * Equality check
   */
  equals(other: Transcript): boolean {
    return this._id === other._id;
  }

  /**
   * String representation
   */
  toString(): string {
    return `Transcript(videoId: ${this._videoId.value}, language: ${this._language.code}, segments: ${this._segments.length}, duration: ${this.durationFormatted})`;
  }

  /**
   * JSON serialization for storage
   */
  toJSON(): {
    id: string;
    videoId: string;
    language: string;
    source: TranscriptSource;
    segments: { text: string; start: number; duration: number }[];
    fetchedAt: string;
    isAutoGenerated: boolean;
  } {
    return {
      id: this._id,
      videoId: this._videoId.value,
      language: this._language.code,
      source: this._source,
      segments: this._segments.map((s) => s.toJSON()),
      fetchedAt: this._fetchedAt.toISOString(),
      isAutoGenerated: this._isAutoGenerated,
    };
  }
}

/**
 * Type guard for Transcript
 */
export function isTranscript(value: unknown): value is Transcript {
  return value instanceof Transcript;
}
