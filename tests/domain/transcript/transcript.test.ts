/**
 * Transcript Entity Tests
 */

import { AppError, ErrorCodes } from '@core/errors/index.js';
import { LanguageCode } from '@domain/transcript/language-code.js';
import { TranscriptSegment } from '@domain/transcript/transcript-segment.js';
import { Transcript } from '@domain/transcript/transcript.js';
import { VideoId } from '@domain/transcript/video-id.js';
import { describe, expect, it } from 'vitest';

const createTestSegments = (count: number = 3) => {
  return Array.from({ length: count }, (_, i) =>
    TranscriptSegment.createUnsafe(`Segment ${i + 1}`, i * 10, 5)
  );
};

describe('Transcript', () => {
  describe('create', () => {
    it('should create transcript from valid segments', () => {
      const videoId = VideoId.createUnsafe('dQw4w9WgXcQ');
      const language = LanguageCode.createUnsafe('en');
      const segments = createTestSegments(3);

      const result = Transcript.create(videoId, language, 'youtube-transcript-api', segments);
      expect(result.ok).toBe(true);
      expect(result.value.segmentCount).toBe(3);
      expect(result.value.videoId).toBe(videoId);
      expect(result.value.language).toBe(language);
      expect(result.value.source).toBe('youtube-transcript-api');
    });

    it('should reject empty segments', () => {
      const videoId = VideoId.createUnsafe('dQw4w9WgXcQ');
      const language = LanguageCode.createUnsafe('en');

      const result = Transcript.create(videoId, language, 'youtube-transcript-api', []);
      expect(result.ok).toBe(false);
      expect(result.error.code).toBe(ErrorCodes.TRANSCRIPT_EMPTY);
    });

    it('should reject overlapping segments', () => {
      const videoId = VideoId.createUnsafe('dQw4w9WgXcQ');
      const language = LanguageCode.createUnsafe('en');
      const segments = [
        TranscriptSegment.createUnsafe('First', 0, 10),
        TranscriptSegment.createUnsafe('Second', 5, 10), // overlaps
      ];

      const result = Transcript.create(videoId, language, 'youtube-transcript-api', segments);
      expect(result.ok).toBe(false);
      expect(result.error.code).toBe(ErrorCodes.TRANSCRIPT_PARSE_FAILED);
    });

    it('should sort segments by start time', () => {
      const videoId = VideoId.createUnsafe('dQw4w9WgXcQ');
      const language = LanguageCode.createUnsafe('en');
      const segments = [
        TranscriptSegment.createUnsafe('Third', 20, 5),
        TranscriptSegment.createUnsafe('First', 0, 5),
        TranscriptSegment.createUnsafe('Second', 10, 5),
      ];

      const result = Transcript.create(videoId, language, 'youtube-transcript-api', segments);
      expect(result.ok).toBe(true);
      expect(result.value.segments[0].text).toBe('First');
      expect(result.value.segments[1].text).toBe('Second');
      expect(result.value.segments[2].text).toBe('Third');
    });

    it('should set auto-generated flag', () => {
      const videoId = VideoId.createUnsafe('dQw4w9WgXcQ');
      const language = LanguageCode.createUnsafe('en');
      const segments = createTestSegments(1);

      const result = Transcript.create(videoId, language, 'youtube-transcript-api', segments, {
        isAutoGenerated: true,
      });
      expect(result.ok).toBe(true);
      expect(result.value.isAutoGenerated).toBe(true);
    });
  });

  describe('reconstruct', () => {
    it('should reconstruct from stored data', () => {
      const videoId = VideoId.createUnsafe('dQw4w9WgXcQ');
      const language = LanguageCode.createUnsafe('en');
      const segments = createTestSegments(2);
      const transcript = Transcript.create(
        videoId,
        language,
        'youtube-transcript-api',
        segments
      ).value;

      const data = transcript.toJSON();
      const result = Transcript.reconstruct(data);
      expect(result.ok).toBe(true);
      expect(result.value.id).toBe(transcript.id);
      expect(result.value.segmentCount).toBe(2);
      expect(result.value.fullText).toBe('Segment 1 Segment 2');
    });
  });

  describe('properties', () => {
    const videoId = VideoId.createUnsafe('dQw4w9WgXcQ');
    const language = LanguageCode.createUnsafe('en');
    const segments = createTestSegments(3); // 0-5, 10-15, 20-25
    const transcript = Transcript.create(
      videoId,
      language,
      'youtube-transcript-api',
      segments
    ).value;

    it('should return correct full text', () => {
      expect(transcript.fullText).toBe('Segment 1 Segment 2 Segment 3');
    });

    it('should return correct word count', () => {
      expect(transcript.wordCount).toBe(6); // "Segment 1" x3 = 2 words each
    });

    it('should return correct char count', () => {
      expect(transcript.charCount).toBe(transcript.fullText.length);
    });

    it('should return correct duration', () => {
      expect(transcript.duration).toBe(25); // last segment ends at 25
    });

    it('should format duration correctly', () => {
      expect(transcript.durationFormatted).toBe('00:25');
    });

    it('should format hour duration correctly', () => {
      // Create a transcript with hour-long content
      const hourSegments = [
        TranscriptSegment.createUnsafe('Start', 0, 5),
        TranscriptSegment.createUnsafe('End', 3600, 5), // 1 hour
      ];
      const hourTranscript = Transcript.create(videoId, language, 'test', hourSegments).value;
      expect(hourTranscript.durationFormatted).toBe('01:00:05');
    });
  });

  describe('getSegmentAt', () => {
    const videoId = VideoId.createUnsafe('dQw4w9WgXcQ');
    const language = LanguageCode.createUnsafe('en');
    const segments = [
      TranscriptSegment.createUnsafe('First', 0, 10),
      TranscriptSegment.createUnsafe('Second', 10, 10),
      TranscriptSegment.createUnsafe('Third', 20, 10),
    ];
    const transcript = Transcript.create(videoId, language, 'test', segments).value;

    it('should return segment at exact start', () => {
      const seg = transcript.getSegmentAt(0);
      expect(seg).toBeDefined();
      expect(seg?.text).toBe('First');
    });

    it('should return segment in middle', () => {
      const seg = transcript.getSegmentAt(15);
      expect(seg).toBeDefined();
      expect(seg?.text).toBe('Second');
    });

    it('should return undefined for time before first segment', () => {
      const seg = transcript.getSegmentAt(-1);
      expect(seg).toBeUndefined();
    });

    it('should return undefined for time after last segment', () => {
      const seg = transcript.getSegmentAt(100);
      expect(seg).toBeUndefined();
    });
  });

  describe('getSegmentsInRange', () => {
    const videoId = VideoId.createUnsafe('dQw4w9WgXcQ');
    const language = LanguageCode.createUnsafe('en');
    const segments = [
      TranscriptSegment.createUnsafe('First', 0, 10),
      TranscriptSegment.createUnsafe('Second', 10, 10),
      TranscriptSegment.createUnsafe('Third', 20, 10),
    ];
    const transcript = Transcript.create(videoId, language, 'test', segments).value;

    it('should return segments overlapping with range', () => {
      // Range 5-25 overlaps with all three segments (0-10, 10-20, 20-30)
      const segs = transcript.getSegmentsInRange(5, 25);
      expect(segs).toHaveLength(3);
      expect(segs[0].text).toBe('First');
      expect(segs[1].text).toBe('Second');
      expect(segs[2].text).toBe('Third');
    });

    it('should return empty array for no overlap', () => {
      const segs = transcript.getSegmentsInRange(50, 60);
      expect(segs).toHaveLength(0);
    });
  });

  describe('getTextInRange', () => {
    const videoId = VideoId.createUnsafe('dQw4w9WgXcQ');
    const language = LanguageCode.createUnsafe('en');
    const segments = [
      TranscriptSegment.createUnsafe('First', 0, 10),
      TranscriptSegment.createUnsafe('Second', 10, 10),
    ];
    const transcript = Transcript.create(videoId, language, 'test', segments).value;

    it('should return concatenated text in range', () => {
      const text = transcript.getTextInRange(0, 20);
      expect(text).toBe('First Second');
    });
  });

  describe('chunkByTokens', () => {
    const videoId = VideoId.createUnsafe('dQw4w9WgXcQ');
    const language = LanguageCode.createUnsafe('en');
    // Create segments with longer text to ensure chunking occurs
    const segments = Array.from({ length: 10 }, (_, i) =>
      TranscriptSegment.createUnsafe(
        `Segment ${i + 1} with some text content that is longer to test chunking functionality properly`,
        i * 5,
        5
      )
    );
    const transcript = Transcript.create(videoId, language, 'test', segments).value;

    it('should split into chunks', () => {
      const chunks = transcript.chunkByTokens(50); // ~200 chars per chunk
      expect(chunks.length).toBeGreaterThan(1);
    });

    it('should include all segments across chunks', () => {
      const chunks = transcript.chunkByTokens(50);
      const allSegments = chunks.flatMap((c) => c.segments);
      expect(allSegments.length).toBe(10);
    });
  });

  describe('toJSON', () => {
    it('should serialize correctly', () => {
      const videoId = VideoId.createUnsafe('dQw4w9WgXcQ');
      const language = LanguageCode.createUnsafe('en');
      const segments = createTestSegments(2);
      const transcript = Transcript.create(videoId, language, 'test', segments).value;

      const json = transcript.toJSON();
      expect(json.id).toBe(transcript.id);
      expect(json.videoId).toBe('dQw4w9WgXcQ');
      expect(json.language).toBe('en');
      expect(json.source).toBe('test');
      expect(json.segments).toHaveLength(2);
      expect(json.fetchedAt).toBeDefined();
      expect(json.isAutoGenerated).toBe(false);
    });
  });
});
